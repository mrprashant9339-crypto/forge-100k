import { chromium } from "playwright";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";

const base = process.env.FORGE_BASE_URL || "http://127.0.0.1:4173";
const browser = await chromium.launch({headless:true,args:["--no-sandbox","--use-gl=angle","--use-angle=swiftshader","--enable-webgl","--ignore-gpu-blocklist"]});
const page = await browser.newPage({acceptDownloads:true});
const errors=[];
page.on("pageerror",e=>errors.push(e.message));
try {
  await page.goto(base,{waitUntil:"networkidle",timeout:60000});
  await page.locator("#view canvas").waitFor({state:"visible",timeout:30000});
  await page.waitForFunction(()=>!document.querySelector("#previewTitle")?.textContent.includes("Loading preview"));
  if (!(await page.locator("#cards .asset").count())) throw new Error("Character catalogue did not render");
  await page.locator("#authButton").click();
  await page.locator("#authModal").waitFor({state:"visible"});
  if (await page.locator("#authNameField").isVisible()) throw new Error("Login form should not show the sign-up name field");
  await page.locator("#authSignupLink").click();
  if (!(await page.locator("#authNameField").isVisible())) throw new Error("Sign-up form did not reveal the full-name field");
  await page.locator("#authEmail").fill("test@example.com");
  await page.locator("#authName").fill("Forge Test");
  await page.locator("#authPassword").fill("test-password-12345");
  await page.locator("#authConfirm").fill("test-password-12345");
  await page.locator("#authSubmit").click();
  await page.locator("#authModal").waitFor({state:"hidden",timeout:10000});
  await page.locator("#authButton").filter({hasText:"Account"}).waitFor({timeout:5000});
  await page.locator("#authLoginLink").click();
  await page.locator("#authResetLink").click();
  if (await page.locator("#authPasswordField").isVisible()) throw new Error("Local password help must not expose a password input");
  await page.getByText(/local-only|local admin reset/i).waitFor({timeout:5000});
  await page.locator("#authClose").click();
  await page.locator("#categorySearch").fill("Birds");
  if (!(await page.locator('#cats [data-cat="Birds"]').count())) throw new Error("Category search did not filter the category list");
  await page.locator("#categorySearch").fill("");
  await page.locator('#cats [data-cat="All assets"]').click();
  await page.locator("#save").click();
  const guestPresets = await page.evaluate(() => localStorage.getItem("forge100k:guest"));
  if (!guestPresets || !JSON.parse(guestPresets).length) throw new Error("Guest preset was not saved to its isolated storage namespace");
  if (!(await page.locator("#savedList .saved-load").count())) throw new Error("Saved preset manager did not render the saved item");
  await page.locator("#savedList .saved-load").first().click();
  await page.locator("#wireToggle").click();
  if (await page.locator("#wireToggle").getAttribute("aria-pressed") !== "true") throw new Error("Wireframe toggle did not activate");
  await page.locator("#resetView").click();
  await page.locator("#savedList .saved-delete").first().click();
  if ((await page.locator("#savedList .saved-load").count()) !== 0) throw new Error("Saved preset delete action did not remove the item");

  await page.locator("#apply").click();
  await page.locator("#outfit").selectOption("Armored");
  await page.locator("#apply").click();
  const downloadPromise=page.waitForEvent("download",{timeout:30000});
  await page.locator("#download").click();
  const download=await downloadPromise;
  const target=path.join(os.tmpdir(),download.suggestedFilename());
  await download.saveAs(target);
  const bytes=await fs.readFile(target);
  if (bytes.length<20 || bytes.subarray(0,4).toString("ascii")!=="glTF") throw new Error("GLB export did not produce a valid GLB header");
  await page.locator("#file").setInputFiles(target);
  await page.getByText("GLB loaded",{exact:true}).waitFor({timeout:30000});

  await page.goto(base+"/motion-lab.html?asset=FG-000042&name=Test%20Preset&style=Royal",{waitUntil:"networkidle",timeout:60000});
  await page.locator("#stage canvas").waitFor({state:"visible",timeout:30000});
  if (!(await page.locator("#characterMeta").textContent()).includes("FG-000042")) throw new Error("Motion Lab did not receive the selected catalogue preset identity");
  await page.locator('[data-clip="walk"]').click();
  if (!(await page.locator("#clipName").textContent()).includes("WALK")) throw new Error("Motion clip selection did not update");
  await page.locator("#gravity").evaluate(el=>{el.value="12";el.dispatchEvent(new Event("input",{bubbles:true}))});
  if (!(await page.locator("#gravityValue").textContent()).includes("12.0")) throw new Error("Gravity control did not update");
  await page.locator('[data-clip="jump"]').click();
  await page.locator("#play").click();
  const motionDownloadPromise=page.waitForEvent("download",{timeout:30000});
  await page.locator("#exportMotion").click();
  const motionDownload=await motionDownloadPromise;
  const motionPath=path.join(os.tmpdir(),motionDownload.suggestedFilename());
  await motionDownload.saveAs(motionPath);
  const motionData=JSON.parse(await fs.readFile(motionPath,"utf8"));
  if(motionData.schema!=="forge.motion.v1" || motionData.clip!=="jump" || motionData.simulation.gravityMps2!==12) throw new Error("Motion JSON export failed schema or parameter checks");
  await fs.rm(motionPath,{force:true});
  if(errors.length) throw new Error("Browser errors: "+errors.join(" | "));
  console.log(JSON.stringify({status:"pass",canvas:true,catalogue:true,glbBytes:bytes.length,glbMagic:bytes.subarray(0,4).toString("ascii"),uploadPreview:true}));
  await fs.rm(target,{force:true});
} finally {
  await browser.close();
}
